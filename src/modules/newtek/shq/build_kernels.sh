#!/bin/sh
# Rebuilds shq_kernels_fatbin.h from shq_kernels.cu with nvcc in a CUDA container, so neither the
# build host nor the server needs the CUDA toolkit. Commit the generated header with the .cu.
#
# Cubins for Turing, Ampere (the RTX A2000 is sm_86) and Ada, plus compute_75 PTX that newer
# drivers compile for later GPUs.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
image=${CUDA_IMAGE:-nvidia/cuda:12.8.1-devel-ubuntu24.04}

docker run --rm -v "$here:/src" -w /src "$image" \
    nvcc -O3 --fatbin -std=c++17 \
        -gencode arch=compute_75,code=sm_75 \
        -gencode arch=compute_86,code=sm_86 \
        -gencode arch=compute_89,code=sm_89 \
        -gencode arch=compute_75,code=compute_75 \
        -o /src/shq_kernels.fatbin shq_kernels.cu

python3 - "$here/shq_kernels.fatbin" "$here/shq_kernels_fatbin.h" <<'EOF'
import sys
data = open(sys.argv[1], "rb").read()
lines = []
for i in range(0, len(data), 20):
    lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
with open(sys.argv[2], "w") as out:
    out.write("// Generated by build_kernels.sh from shq_kernels.cu. Do not edit.\n")
    out.write("#pragma once\n\n")
    out.write("alignas(16) static const unsigned char shq_kernels_fatbin[] = {\n")
    out.write("\n".join(lines))
    out.write("\n};\n")
EOF
rm "$here/shq_kernels.fatbin"
echo "wrote $here/shq_kernels_fatbin.h"
